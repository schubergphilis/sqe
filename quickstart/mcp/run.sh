#!/usr/bin/env bash
# Reuse the Polaris + Keycloak user-token stack, enable MCP, seed data and test.
set -euo pipefail
cd "$(dirname "$0")"
. ../_shared/lib.sh

CHECK=0
WRITES=0
for arg in "$@"; do
  case "$arg" in
    --check) CHECK=1 ;;
    --writes) WRITES=1 ;;
    --down)
      require docker
      docker compose --env-file .env -p sqe-mcp \
        -f ../polaris-keycloak-user-token/docker-compose.yml \
        -f docker-compose.yml down -v
      exit 0
      ;;
    *) die "unknown arg: $arg (use --check, --writes, or --down)" ;;
  esac
done

require docker curl jq
[ -f .env ] || { step "creating .env from .env.example"; cp .env.example .env; }
set -a; . ./.env; set +a
if [ "$WRITES" -eq 1 ]; then export MCP_ALLOW_WRITES=true; fi

COMPOSE=(docker compose --env-file .env -p sqe-mcp
  -f ../polaris-keycloak-user-token/docker-compose.yml
  -f docker-compose.yml)

step "starting the reused Keycloak + Polaris + RustFS stack and SQE MCP"
"${COMPOSE[@]}" up -d --build --wait
ok "stack ready; MCP is sharing SQE web port ${SQE_MCP_PORT:-19091}"

step "minting short-lived per-user tokens"
SQE_MCP_TOKEN=$(./mint-token.sh adminuser adminuser123 "openid sqe:mcp:write")
SQE_MCP_READER_TOKEN=$(./mint-token.sh testuser testuser123 "openid sqe:mcp:write")
export SQE_MCP_TOKEN SQE_MCP_READER_TOKEN
ok "adminuser and testuser tokens minted"

step "seeding the reusable quickstart table through Flight SQL as adminuser"
"${COMPOSE[@]}" exec -T sqe sqe-cli --port 50051 --token "$SQE_MCP_TOKEN" \
  --file /queries.sql --stop-on-error >/dev/null
ok "quickstart.demo.events contains four rows"

export SQE_MCP_URL="http://localhost:${SQE_MCP_PORT:-19091}/mcp"
if [ "$WRITES" -eq 1 ]; then export EXPECT_WRITES=true; else export EXPECT_WRITES=false; fi

if [ "$CHECK" -eq 1 ]; then
  ./test-mcp.sh
else
  {
    echo "# Captured MCP quickstart output"
    echo
    echo "Generated by ./run.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
    echo
    ./test-mcp.sh
  } 2>&1 | tee OUTPUT.md
fi

echo
ok "try Codex/Claude: export SQE_MCP_TOKEN=\"\$(./mint-token.sh)\""
ok "then run ./setup-client.sh codex or ./setup-client.sh claude"
